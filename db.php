//$host**: Onde está o servidor? No nosso caso, é `'localhost'` (a sua própria máquina).
$dbname**: Qual é o nome do banco? É `'gerenciador_tarefas'` (o nome exato que definimos no `banco.sql`).
* **$user**: Qual o usuário do banco? No XAMPP, o padrão é `'root'`.
* **$pass**: Qual a senha? No XAMPP padrão, a senha é **vazia** (`''`).